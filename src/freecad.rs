//! The FreeCAD engine: emit a real macro, and run it where FreeCAD exists.
//!
//! This is the engine that can actually cut material, round an edge and export
//! a STEP part. It is the intended production backend; the native engine exists
//! so the round trip can be tested anywhere, including machines without a CAD
//! kernel installed.

use crate::ops::{Op, Profile, Program};
use std::path::{Path, PathBuf};

/// Where the FreeCAD command line lives on this machine, if anywhere.
pub fn command() -> Option<String> {
    for name in ["freecadcmd", "FreeCADCmd", "freecad"] {
        if let Some(p) = which(name) {
            return Some(p);
        }
    }
    None
}

fn which(name: &str) -> Option<String> {
    let path = std::env::var("PATH").ok()?;
    for dir in path.split(':') {
        if dir.is_empty() {
            continue;
        }
        let full = Path::new(dir).join(name);
        if full.is_file() {
            return Some(full.to_string_lossy().into_owned());
        }
    }
    None
}

fn tup(v: &[f64; 3]) -> String {
    format!("({:.6}, {:.6}, {:.6})", v[0], v[1], v[2])
}

fn label(op: &Op) -> &'static str {
    match op {
        Op::Extrude { .. } => "extrude",
        Op::Hole { .. } => "hole",
        Op::HolePattern { .. } => "hole pattern",
        Op::Fillet { .. } => "fillet",
    }
}

/// Translate a program into a FreeCAD Python macro.
pub fn script(program: &Program, out_dir: &Path) -> Result<String, String> {
    program.validate()?;
    let out = out_dir.to_string_lossy().replace('\\', "/");
    let mut s = String::new();
    s.push_str("# Generated by cadforge. Executes an operation program and exports the part.\n");
    s.push_str("import os\nimport FreeCAD\nimport Part\n\n");
    s.push_str(&format!("OUT = r\"{out}\"\n"));
    s.push_str("def hole(shape, at, axis, radius, depth=None):\n");
    s.push_str("    a = FreeCAD.Vector(axis[0], axis[1], axis[2]).normalize()\n");
    s.push_str("    length = depth if depth else shape.BoundBox.DiagonalLength * 2.0\n");
    s.push_str("    start = FreeCAD.Vector(at[0], at[1], at[2])\n");
    s.push_str("    if depth is None:\n");
    s.push_str("        start = start - a * (length / 2.0)\n");
    s.push_str("    return shape.cut(Part.makeCylinder(radius, length, start, a))\n\n");
    s.push_str("DOC = FreeCAD.newDocument(\"cadforge\")\nshape = None\n\n");

    for (i, op) in program.ops.iter().enumerate() {
        s.push_str(&format!("# op {}: {}\n", i + 1, label(op)));
        match op {
            Op::Extrude {
                profile,
                distance,
                direction,
            } => match profile {
                Profile::Polygon { points } => {
                    let pts: Vec<String> = points.iter().map(tup).collect();
                    let mut closed = pts.clone();
                    if let Some(first) = pts.first() {
                        closed.push(first.clone());
                    }
                    s.push_str(&format!(
                        "_wire = Part.makePolygon([{}])\n",
                        closed.join(", ")
                    ));
                    s.push_str("_solid = Part.Face(_wire).extrude(FreeCAD.Vector(");
                    s.push_str(&format!(
                        "{:.6}, {:.6}, {:.6}))\n",
                        direction[0] * distance,
                        direction[1] * distance,
                        direction[2] * distance
                    ));
                    s.push_str("shape = _solid if shape is None else shape.fuse(_solid)\n\n");
                }
                Profile::Circle {
                    center, diameter, ..
                } => {
                    s.push_str(&format!(
                        "_solid = Part.makeCylinder({:.6}, {:.6}, FreeCAD.Vector{}, FreeCAD.Vector{})\n",
                        diameter / 2.0,
                        distance,
                        tup(center),
                        tup(direction)
                    ));
                    s.push_str("shape = _solid if shape is None else shape.fuse(_solid)\n\n");
                }
            },
            Op::Hole {
                diameter,
                through,
                depth,
                at,
                axis,
            } => {
                let d = if *through {
                    "None".to_string()
                } else {
                    format!("{:.6}", depth)
                };
                s.push_str(&format!(
                    "shape = hole(shape, {}, {}, {:.6}, {})\n\n",
                    tup(at),
                    tup(axis),
                    diameter / 2.0,
                    d
                ));
            }
            Op::HolePattern {
                diameter,
                through,
                depth,
                positions,
                axis,
            } => {
                let d = if *through {
                    "None".to_string()
                } else {
                    format!("{:.6}", depth)
                };
                s.push_str("for _p in [");
                let items: Vec<String> = positions.iter().map(tup).collect();
                s.push_str(&items.join(", "));
                s.push_str("]:\n");
                s.push_str(&format!(
                    "    shape = hole(shape, _p, {}, {:.6}, {})\n\n",
                    tup(axis),
                    diameter / 2.0,
                    d
                ));
            }
            Op::Fillet { radius } => {
                s.push_str(&format!(
                    "shape = shape.makeFillet({:.6}, shape.Edges)\n\n",
                    radius
                ));
            }
        }
    }

    s.push_str("Part.show(shape, \"cadforge_part\")\n");
    s.push_str("os.makedirs(OUT, exist_ok=True)\n");
    s.push_str("shape.exportStep(os.path.join(OUT, \"rebuilt.step\"))\n");
    s.push_str("shape.exportStl(os.path.join(OUT, \"rebuilt.stl\"))\n");
    s.push_str("FreeCAD.closeDocument(DOC.Name)\n");
    s.push_str("print(\"cadforge: exported\", os.path.join(OUT, \"rebuilt.stl\"))\n");
    Ok(s)
}

/// Write the macro, run it with the local FreeCAD, and return what it printed.
pub fn run(program: &Program, out_dir: &Path) -> Result<String, String> {
    let exe = command().ok_or_else(|| {
        "FreeCAD is not installed on this machine (no freecadcmd on PATH)".to_string()
    })?;
    std::fs::create_dir_all(out_dir).map_err(|e| e.to_string())?;
    let script_path: PathBuf = out_dir.join("rebuild.py");
    std::fs::write(&script_path, script(program, out_dir)?).map_err(|e| e.to_string())?;

    let out = std::process::Command::new(&exe)
        .arg(&script_path)
        .output()
        .map_err(|e| format!("could not run {exe}: {e}"))?;
    let stdout = String::from_utf8_lossy(&out.stdout).into_owned();
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    if !out.status.success() {
        return Err(format!(
            "FreeCAD failed: {}",
            if stderr.is_empty() { stdout } else { stderr }
        ));
    }
    Ok(stdout)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::ops::{Op, Profile, Program, VERSION};

    fn plate() -> Program {
        Program {
            version: VERSION,
            units: "mm".into(),
            ops: vec![
                Op::Extrude {
                    profile: Profile::Polygon {
                        points: vec![
                            [0.0, 0.0, 0.0],
                            [60.0, 0.0, 0.0],
                            [60.0, 40.0, 0.0],
                            [0.0, 40.0, 0.0],
                        ],
                    },
                    distance: 8.0,
                    direction: [0.0, 0.0, 1.0],
                },
                Op::HolePattern {
                    diameter: 6.0,
                    through: true,
                    depth: 0.0,
                    positions: vec![[12.0, 10.0, 0.0], [48.0, 10.0, 0.0]],
                    axis: [0.0, 0.0, 1.0],
                },
            ],
        }
    }

    #[test]
    fn emits_a_runnable_macro() {
        let s = script(&plate(), std::path::Path::new("/tmp/cadforge-test")).unwrap();
        assert!(s.contains("import FreeCAD"));
        assert!(s.contains("Part.makePolygon"));
        assert!(s.contains("Part.Face(_wire).extrude"));
        assert!(s.contains("for _p in [(12.000000, 10.000000, 0.000000)"));
        assert!(s.contains("shape = hole(shape, _p,"));
        assert!(s.contains("exportStep"));
        assert!(s.contains("exportStl"));
    }

    #[test]
    fn refuses_an_invalid_program() {
        let mut p = plate();
        p.ops.push(Op::Fillet { radius: -1.0 });
        assert!(script(&p, std::path::Path::new("/tmp")).is_err());
    }
}
